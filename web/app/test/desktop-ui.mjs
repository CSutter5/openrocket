import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { chromium } from 'playwright';
import { output } from './fixtures.mjs';
import { openSample, openProperties, flights } from './workspace.mjs';
const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_EXECUTABLE ? { executablePath: process.env.CHROMIUM_EXECUTABLE } : {}) });
await mkdir(output, { recursive: true });
const checks = [], errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.ORK_POC_URL || 'http://127.0.0.1:5173');
  const design = page.getByRole('tab', { name: 'Rocket design', exact: true });
  const drawing = page.getByRole('region', { name: 'Rocket drawing', exact: true });
  await drawing.locator('polygon').first().waitFor();
  assert.equal(await page.getByRole('dialog').count(), 0);
  const treeBox = await page.getByRole('navigation', { name: 'Component tree' }).boundingBox();
  const drawingBox = await drawing.boundingBox();
  assert.ok(treeBox.y + treeBox.height < drawingBox.y, 'tree is above the persistent drawing');
  for (const image of await page.locator('.component-icon').all()) assert.ok(await image.evaluate(node => node instanceof HTMLImageElement && node.complete && node.naturalWidth > 0));
  assert.equal(await page.getByRole('region', { name: 'Add new component' }).getByRole('button', { name: 'Body tube', exact: true }).isDisabled(), true);
  const points = await drawing.locator('polygon').evaluateAll(nodes => nodes.map(n => n.getAttribute('points')));
  const part = drawing.locator('polygon').first(), beforeZoom = await part.boundingBox();
  await drawing.getByRole('button', { name: 'Zoom in', exact: true }).click();
  assert.ok((await part.boundingBox()).width > beforeZoom.width * 1.2);
  await drawing.getByRole('button', { name: '125% · Fit', exact: true }).click();
  assert.deepEqual(await drawing.locator('polygon').evaluateAll(nodes => nodes.map(n => n.getAttribute('points'))), points);
  await design.focus(); await page.keyboard.press('ArrowRight');
  assert.equal(await page.getByRole('tab', { name: 'Motors & Configuration' }).getAttribute('aria-selected'), 'true');
  assert.ok(await drawing.isVisible());
  await page.keyboard.press('End');
  assert.equal(await page.getByRole('tab', { name: 'Flight simulations', exact: true }).getAttribute('aria-selected'), 'true');
  await page.keyboard.press('Home');
  assert.equal(await design.getAttribute('aria-selected'), 'true');
  assert.ok(await part.evaluate(node => { const bounds = node.getBoundingClientRect(), canvas = node.closest('.drawing-canvas').getBoundingClientRect(); return bounds.top >= canvas.top && bounds.bottom <= canvas.bottom; }), 'fit keeps the rocket within the canvas');
  checks.push('desktop layout, original component icons, disabled unsupported palette, zoom, keyboard tabs, persistent drawing');

  await page.getByRole('button', { name: 'Body tube bodytube', exact: true }).dblclick();
  const editor = page.getByRole('dialog', { name: 'Component editor', exact: true });
  await editor.getByLabel('Component name', { exact: true }).fill('Draft component');
  await editor.press('Escape');
  assert.equal(await editor.count(), 0);
  assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Body tube bodytube');
  await openProperties(page);
  assert.equal(await editor.getByLabel('Component name', { exact: true }).inputValue(), 'Body tube');
  await editor.getByRole('button', { name: 'Close Component editor', exact: true }).click();
  checks.push('double-click component editor, Escape, focus restoration, unapplied draft discarded');

  await page.getByLabel('Open local .ork').setInputFiles(resolve(output, 'explicit/G1-A.ork'));
  await page.getByText('G1-A.ork', { exact: true }).waitFor();
  await page.getByRole('tab', { name: 'Motors & Configuration' }).click();
  const config = page.getByLabel('Flight configuration', { exact: true });
  const original = await config.inputValue(), choices = await config.locator('option').evaluateAll(nodes => nodes.map(n => ({ id: n.value, label: n.textContent })));
  assert.ok(choices.length > 1);
  await page.getByRole('button', { name: 'Select motor', exact: true }).click();
  const selector = page.getByRole('dialog', { name: 'Select motor', exact: true });
  await selector.getByLabel('Search motors').fill('no matching motor');
  await selector.getByText('No matching motors.', { exact: true }).waitFor();
  await selector.getByLabel('Search motors').fill('');
  await selector.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(await config.inputValue(), original);
  await config.selectOption(choices[1].id);
  await page.getByRole('status').filter({ hasText: 'Session flight configuration selected.' }).waitFor();
  assert.equal(await config.inputValue(), choices[1].id);
  await page.getByTestId('dirty').filter({ hasText: 'No changes since' }).waitFor();
  await flights(page);
  assert.equal(await page.getByLabel('Motor configuration', { exact: true }).count(), 0);
  const event = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download .ork', exact: true }).click();
  assert.deepEqual(await readFile(await (await event).path()), await readFile(resolve(output, 'explicit/G1-A.ork')));
  checks.push('catalog-only search/cancel, configuration selection in toolbar, byte-identical export and no session simulation row');

  await page.getByLabel('Open local .ork').setInputFiles(resolve(output, 'saved-conditions.ork'));
  await page.getByText('saved-conditions.ork', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Run flight', exact: true }).click();
  await design.click();
  await page.getByTestId('flight-status').filter({ hasText: 'Flight completed.' }).waitFor({ state: 'attached', timeout: 60000 });
  await flights(page);
  await page.getByTestId('flight-status').filter({ hasText: 'Flight completed.' }).waitFor();
  await page.locator('.simulation-table').getByText('Completed', { exact: true }).waitFor();
  await page.screenshot({ path: resolve(output, 'desktop-simulations.png') });
  checks.push('saved flight continues across workspace tabs and updates its own simulation row');
  await design.click();
  await page.screenshot({ path: resolve(output, 'desktop-design.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'no page overflow at phone width');
  await openProperties(page);
  const box = await editor.boundingBox();
  assert.ok(box.x >= 0 && box.x + box.width <= 390);
  await editor.getByLabel('Component name', { exact: true }).fill('Mobile draft');
  await editor.getByRole('button', { name: 'Close Component editor', exact: true }).click();
  await page.screenshot({ path: resolve(output, 'desktop-mobile.png') });
  checks.push('phone viewport, usable component fields and dialog close, no horizontal page overflow');
  assert.deepEqual(errors, []);
  await writeFile(resolve(output, 'desktop-ui-report.json'), JSON.stringify({ outcome: 'passed', browser: browser.version(), checks, pageErrors: errors }, null, 2) + '\n');
  console.log('Desktop-style workspace browser interactions passed: ' + checks.join('; '));
} finally { await browser.close(); }
